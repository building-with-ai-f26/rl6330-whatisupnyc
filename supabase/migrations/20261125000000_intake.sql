-- Events another tool sends in (POST /api/intake), waiting for the morning collection to check them
-- on their official page. Only the server reads or writes this table.
create table intake_events (
    id bigint generated by default as identity primary key,
    post_url text not null unique,      -- where it was found; stored, never fetched
    name text not null,
    start timestamptz not null,
    venue text not null,
    address text,
    official_url text,                  -- the page the collector checks
    caption text,
    price text,
    category text,
    received_at timestamptz not null,
    received_day date not null,         -- New York day, for the daily cap
    checked_at timestamptz              -- set once the morning collection has handled it
);

alter table intake_events enable row level security;
revoke all on intake_events from anon, authenticated;
